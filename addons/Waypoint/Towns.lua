-- The badges' frame level: above every layer that covers the whole map (the explored subzones'
-- painted art is one, and it paints over anything at or below its level: a badge on an explored
-- town vanished under it), but under Waypoint's own path and target pins (+2100). Layers at or
-- over that line are left out, so none can lift the badges over Waypoint's pins.
local LAYER_CAP = 2090
BadgeLevel = function(canvas)
    local base = canvas:GetFrameLevel()
    local level = base + 1999
    for _, f in ipairs({ canvas:GetChildren() }) do
        if not f.wpTown and f:IsVisible() then
            local w, h = f:GetSize()
            local l = f:GetFrameLevel()
            if w > MAX_ICON and h > MAX_ICON and l < base + 2100 and l >= level then level = l + 1 end
        end
    end
    return math.min(level, base + LAYER_CAP)
end

-- Tooltip colours: the town's name, section labels, kinds, names, and the hidden icons' section.
local TITLE, SUB = { 1, 0.82, 0.3 }, { 0.6, 0.65, 0.7 }
local LABEL, KIND, NAMES = { 1, 0.82, 0 }, { 0.92, 0.92, 0.92 }, { 0.62, 0.68, 0.74 }
local ALSO, NPC_COLOR, NOTE = { 0.4, 0.75, 1 }, { 0.45, 0.9, 0.45 }, { 0.7, 0.7, 0.7 }
local FLIGHT_WORDS = { "flight master", "gryphon master", "wind rider master", "hippogryph master", "bat handler" }

-- "A, B, C, D +2 more" -> "A, B +4".
local function Short(names)
    local list, more = {}, tonumber(names:match("%+(%d+) more")) or 0
    for n in (names:gsub("%s*%+%d+ more", "")):gmatch("[^,]+") do list[#list + 1] = strtrim(n) end
    local extra = math.max(0, #list - 2) + more
    return table.concat(list, ", ", 1, math.min(2, #list)) .. (extra > 0 and (" +" .. extra) or "")
end

-- Text with the game's colour codes and icons taken out.
local function Plain(s)
    return strtrim((s or ""):gsub("|T.-|t", ""):gsub("|A.-|a", ""):gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", ""))
end

-- ---------------------------------------------------------------------------------------------
-- What the covered icons hold. Questie's icons carry their data (icon.data: a quest giver's
-- quests, an active quest's objective, a townsfolk note), read straight from there and shown in
-- our own style; with Shift held, Questie's extra detail too (rewards, reputation, the quest's
-- description, what comes next in its chain). Any other addon's icon: what its tooltip says.
-- ---------------------------------------------------------------------------------------------

-- Questie's modules through its loader, or nil (no Questie, or a version that has moved them).
local function QuestieModules()
    if not (QuestieLoader and QuestieLoader.ImportModule and Questie and Questie.db and Questie.db.profile) then return nil end
    local ok, m = pcall(function()
        return { DB = QuestieLoader:ImportModule("QuestieDB"), Lib = QuestieLoader:ImportModule("QuestieLib"),
                 XP = QuestieLoader:ImportModule("QuestXP"), Rep = QuestieLoader:ImportModule("QuestieReputation") }
    end)
    return ok and m or nil
end

local function Try(fn, ...)
    if type(fn) ~= "function" then return nil end
    local ok, a = pcall(fn, ...)
    return ok and a or nil
end

-- A Questie map icon (only with Questie loaded: another addon's pin with a similar .data is read
-- from its tooltip instead).
local function IsQuestieIcon(f)
    local d = Questie ~= nil and f.data
    return type(d) == "table" and (d.Type ~= nil or d.ManualTooltipData ~= nil or d.ObjectiveData ~= nil)
end

-- { givers = { { name, quests = { { id, status, data } } } }, active = { { id, objectives = { text } } },
--   notes = { { title, body = { text } } }, other = { text } } for the icons under a badge.
local function Gather(pin)
    local out, byGiver, byActive, seenQuest, seenNote, seenOther =
        { givers = {}, active = {}, notes = {}, other = {} }, {}, {}, {}, {}, {}
    local M = QuestieModules()
    for frame, h in pairs(hidden) do
        if h.pin == pin then
            local d = frame.data
            if IsQuestieIcon(frame) and (d.Type == "available" or d.Type == "complete") and d.Id then
                local name = d.Name or "?"
                local giver = byGiver[name]
                if not giver then
                    giver = { name = name, quests = {} }
                    byGiver[name] = giver
                    out.givers[#out.givers + 1] = giver
                end
                local known = seenQuest[d.Id]
                if not known then
                    local status = d.Type == "complete" and "complete"
                        or (M and Try(M.DB and M.DB.IsRepeatable, d.Id)) and "repeatable" or "available"
                    known = { id = d.Id, status = status, data = d.QuestData }
                    seenQuest[d.Id] = known
                    giver.quests[#giver.quests + 1] = known
                elseif d.QuestData and not (known.data and known.data.Description) then
                    known.data = d.QuestData -- the same quest on another icon, with more to say
                end
            elseif IsQuestieIcon(frame) and d.ObjectiveData and d.Id then
                local q = byActive[d.Id]
                if not q then
                    q = { id = d.Id, objectives = {}, seen = {} }
                    byActive[d.Id] = q
                    out.active[#out.active + 1] = q
                end
                local o = d.ObjectiveData
                Try(o.Update, o)
                local text = Plain(o.Description)
                if o.Needed then text = ("%s/%s %s"):format(tostring(o.Collected or 0), tostring(o.Needed), text) end
                if text ~= "" and not q.seen[text] then
                    q.seen[text] = true
                    q.objectives[#q.objectives + 1] = text
                end
            elseif IsQuestieIcon(frame) and d.ManualTooltipData then
                local m = d.ManualTooltipData
                local title = Plain(m.Title)
                if title ~= "" and not seenNote[title] then
                    seenNote[title] = true
                    local body = {}
                    for _, b in ipairs(type(m.Body) == "table" and m.Body or {}) do
                        local text = Plain(type(b) == "table" and (tostring(b[1] or "") .. tostring(b[2] or "")) or tostring(b))
                        if text ~= "" then body[#body + 1] = text end
                    end
                    out.notes[#out.notes + 1] = { title = title, body = body }
                end
            else
                for _, l in ipairs(Borrow(frame)) do
                    local text = Plain(l[1])
                    if text ~= "" and not seenOther[text] then
                        seenOther[text] = true
                        out.other[#out.other + 1] = text
                    end
                end
            end
        end
    end
    return out, M
end

-- Already in the town's own section (its NPCs, the mailbox), a flight master, or a bare role.
local function Redundant(text, known)
    local low = text:lower()
    for _, w in ipairs(FLIGHT_WORDS) do if low:find(w, 1, true) then return true end end
    if text:match("^%(.*%)$") then return true end
    local name = strtrim((text:gsub("%s*%(.-%)", "")))
    return #name >= 4 and known:find(name, 1, true) ~= nil
end

local GetCoins = (C_CurrencyInfo and C_CurrencyInfo.GetCoinTextureString) or GetCoinTextureString

-- The covered icons, in our style, under "Also here". Returns whether any quest has Shift details.
local function AddCovered(pin, known)
    local g, M = Gather(pin)
    local shift = IsShiftKeyDown()
    local notes, other = {}, {}
    for _, n in ipairs(g.notes) do if not Redundant(n.title, known) then notes[#notes + 1] = n end end
    for _, text in ipairs(g.other) do if not Redundant(text, known) then other[#other + 1] = text end end
    if #g.givers + #g.active + #notes + #other == 0 then return false end

    local showLevel = Questie and Questie.db and Questie.db.profile and Questie.db.profile.enableTooltipsQuestLevel
    local function Title(id, data)
        return (M and Try(M.Lib and M.Lib.GetColoredQuestName, M.Lib, id, showLevel, false))
            or (data and data.name) or ("Quest " .. id)
    end
    GameTooltip:AddLine(" ")
    GameTooltip:AddLine("Also here", ALSO[1], ALSO[2], ALSO[3])
    local details = false
    for _, giver in ipairs(g.givers) do
        GameTooltip:AddLine("   " .. giver.name, NPC_COLOR[1], NPC_COLOR[2], NPC_COLOR[3])
        for _, q in ipairs(giver.quests) do
            GameTooltip:AddDoubleLine("      " .. Title(q.id, q.data), q.status, 1, 1, 1, NOTE[1], NOTE[2], NOTE[3])
            details = true
            if shift and M then
                -- Rewards, then what the quest asks, then where its chain leads (as Questie shows them).
                local parts = {}
                local xp = Try(M.XP and M.XP.GetQuestLogRewardXP, M.XP, q.id, Questie.db.profile.showQuestXpAtMaxLevel)
                if xp and xp > 0 then parts[#parts + 1] = FormatLargeNumber(xp) .. " xp" end
                local money = Try(M.XP and M.XP.GetQuestRewardMoney, q.id)
                if money and money > 0 and GetCoins then parts[#parts + 1] = GetCoins(money) end
                local rep = Try(M.Rep and M.Rep.GetReputationReward, q.id)
                if rep and next(rep) then
                    local text = Try(M.Rep.GetReputationRewardString, rep)
                    if text then parts[#parts + 1] = Plain(text) end
                end
                if #parts > 0 then GameTooltip:AddLine("         " .. table.concat(parts, "  ·  "), 1, 0.82, 0, true) end
                local desc = q.data and q.data.Description
                for _, line in ipairs(type(desc) == "table" and desc or { desc }) do
                    if type(line) == "string" and line ~= "" then
                        GameTooltip:AddLine("         " .. Plain(line), NOTE[1], NOTE[2], NOTE[3], true)
                    end
                end
                -- Where its chain leads, once, under its own heading. Chains often reuse the quest's
                -- name for every part ("The Swarm Grows" three times), so those are numbered.
                local base = Plain(Title(q.id, q.data)):gsub("^%[[^%]]*%]%s*", "")
                local nextId, hops, part, shown = Try(M.DB and M.DB.QueryQuestSingle, q.id, "nextQuestInChain"), 0, 1, {}
                while nextId and nextId > 0 and hops < 3 and not shown[nextId] do
                    shown[nextId] = true
                    hops = hops + 1
                    if hops == 1 then GameTooltip:AddLine("         Next in chain", 0.86, 0.86, 0.86) end
                    local title = Plain(Title(nextId))
                    if title:gsub("^%[[^%]]*%]%s*", "") == base then
                        part = part + 1
                        title = title .. (" (part %d)"):format(part)
                    end
                    GameTooltip:AddLine("            " .. title, 0.75, 0.75, 0.75)
                    nextId = Try(M.DB.QueryQuestSingle, nextId, "nextQuestInChain")
                end
            end
        end
    end
    if #g.active > 0 then
        GameTooltip:AddLine("   Active quests", NPC_COLOR[1], NPC_COLOR[2], NPC_COLOR[3])
        for _, q in ipairs(g.active) do
            GameTooltip:AddLine("      " .. Title(q.id), 1, 1, 1)
            for _, o in ipairs(q.objectives) do GameTooltip:AddLine("         " .. o, NOTE[1], NOTE[2], NOTE[3], true) end
        end
    end
    for _, n in ipairs(notes) do
        GameTooltip:AddLine("   " .. n.title, KIND[1], KIND[2], KIND[3])
        if shift then
            for _, b in ipairs(n.body) do GameTooltip:AddLine("      " .. b, NOTE[1], NOTE[2], NOTE[3], true) end
        end
    end
    for _, text in ipairs(other) do GameTooltip:AddLine("   " .. text, NOTE[1], NOTE[2], NOTE[3], true) end
    return details
end

-- How many of a town's quest givers have a quest you can take now (Questie's IsDoable: not done,
-- not in your log, your race and class, prerequisites, level), and how many there are in all.
-- available is nil without Questie (then only the total is known).
function Towns:Givers(t)
    local M = t.g and QuestieModules()
    local doable = M and M.DB and M.DB.IsDoable
    if not doable then return nil, t[7] end
    local n = 0
    for _, quests in ipairs(t.g) do
        for _, q in ipairs(quests) do
            if Try(doable, q) then n = n + 1 break end
        end
    end
    return n, t[7]
end

local current -- the badge whose tooltip is showing (Shift redraws it)

local function OnEnter(pin)
    current = pin
    local t = pin.town
    local lines, flight = Towns:Lines(t)

    GameTooltip:SetOwner(pin, "ANCHOR_RIGHT")
    -- The town: its name large at the top, then where and whose.
    GameTooltip:AddLine(t[1], TITLE[1], TITLE[2], TITLE[3])
    local info = C_Map and C_Map.GetMapInfo and C_Map.GetMapInfo(t[2])
    local whose = t[5] == "AH" and "Neutral" or t[5] == "A" and "Alliance town" or "Horde town"
    GameTooltip:AddLine((info and info.name and (info.name .. "  ·  ") or "") .. whose, SUB[1], SUB[2], SUB[3])
    GameTooltip:AddLine(" ")

    -- What's there, one row each.
    local known, givers = {}, false
    for _, l in ipairs(lines) do
        local label, text = l[1], l[2]
        known[#known + 1] = text
        local parts = {}
        for part in text:gmatch("[^;]+") do parts[#parts + 1] = strtrim(part) end
        local grouped = parts[1] and parts[1]:find("%(") ~= nil
        if label == "Quest givers" then
            -- The ones with a quest for you; Shift adds how many there are in all: "3 (18)".
            local available, total = Towns:Givers(t)
            local value = available and (IsShiftKeyDown() and ("%d |cff40ff40(%d)|r"):format(available, total) or tostring(available)) or text
            if available then givers = true end
            GameTooltip:AddDoubleLine(label, value, LABEL[1], LABEL[2], LABEL[3], KIND[1], KIND[2], KIND[3])
        elseif grouped then
            GameTooltip:AddLine(label, LABEL[1], LABEL[2], LABEL[3])
            for _, part in ipairs(parts) do
                local kind, names = part:match("^(.-)%s*%((.*)%)$")
                if kind then
                    GameTooltip:AddDoubleLine("   " .. kind, Short(names), KIND[1], KIND[2], KIND[3], NAMES[1], NAMES[2], NAMES[3])
                else
                    GameTooltip:AddLine("   " .. part, KIND[1], KIND[2], KIND[3])
                end
            end
        elseif #parts > 1 or text:find(",") and not text:find("%+%d+ more") and label ~= "Repair" and label ~= "Bank" and label ~= "Auction House" then
            -- a capital's long list of kinds: wrapped under its label
            GameTooltip:AddLine(label, LABEL[1], LABEL[2], LABEL[3])
            GameTooltip:AddLine("   " .. text, KIND[1], KIND[2], KIND[3], true)
        else
            GameTooltip:AddDoubleLine(label, Short(text), LABEL[1], LABEL[2], LABEL[3], NAMES[1], NAMES[2], NAMES[3])
        end
    end
    if not flight then GameTooltip:AddLine("No flight master", NO_FLIGHT[1], NO_FLIGHT[2], NO_FLIGHT[3]) end

    -- The icons this badge covers, in their own section, without what's already above.
    local details = AddCovered(pin, table.concat(known, "\n") .. "\nMailbox")
    GameTooltip:AddLine(" ")
    if (details or givers) and not IsShiftKeyDown() then
        GameTooltip:AddLine(details and "Hold Shift: quest details" or "Hold Shift: all quest givers", 0.5, 0.5, 0.5)
    end
    GameTooltip:AddLine("Click: navigate here", 0.5, 0.5, 0.5)
    GameTooltip:Show()
end

local function OnLeave()
    current = nil
    GameTooltip:Hide()
end

-- Shift pressed or let go over a badge: show it again with (or without) the quest details.
ns:On("MODIFIER_STATE_CHANGED", function()
    if current and current:IsMouseOver() and GameTooltip:IsOwned(current) then OnEnter(current) end
end)

-- Leads the arrow to a town, as a request.
function Towns:Navigate(t)
    return ns.Targets:SetRequest("Towns", { title = t[1], points = { { mapID = t[2], x = t[3], y = t[4], label = t[1] } }, arrive = 30 })
end

local function OnClick(pin, button)
    if IsControlKeyDown() then
        if button == "LeftButton" then ns.MapPins:AddAtCursor() end
    elseif button == "LeftButton" then
        Towns:Navigate(pin.town)
    elseif button == "RightButton" and WorldMapFrame.NavigateToParentMap then
        WorldMapFrame:NavigateToParentMap()
    end
end

local function GetPin(canvas)
    used = used + 1
    local pin = pins[used]
    if not pin then
        pin = CreateFrame("Button", nil, canvas)
        pin.wpTown = true
        pin:RegisterForClicks("LeftButtonUp", "RightButtonUp")
        pin.icon = pin:CreateTexture(nil, "ARTWORK"); pin.icon:SetAllPoints()
        pin:SetScript("OnEnter", OnEnter)
        pin:SetScript("OnLeave", OnLeave)
        pin:SetScript("OnClick", OnClick)
        pins[used] = pin
    end
    return pin
end

function Towns:Refresh()
    for i = 1, used do pins[i]:Hide() end
    used = 0
    if not (ns.db and ns.db.towns and Available() and WorldMapFrame and WorldMapFrame:IsShown()) then
        self:RestoreAll()
        return
    end
    local mapID = WorldMapFrame:GetMapID()
    local list = mapID and Index()[mapID]
    if list then
        local canvas = WorldMapFrame:GetCanvas()
        local w, h = canvas:GetSize()
        local scale = 1 / (WorldMapFrame:GetCanvasScale() or 1) -- the same size on screen at any zoom (as MapPins)
        local level = BadgeLevel(canvas)
        for _, t in ipairs(list) do
            local pin = GetPin(canvas)
            pin.town = t
            SetBadge(pin.icon, t[5] == "AH" and ICON_NEUTRAL or ICON)
            pin:SetSize(SIZE, SIZE)
            pin:SetScale(scale)
            pin:SetAlpha(1)
            pin:SetFrameLevel(level)
            pin:ClearAllPoints()
            pin:SetPoint("CENTER", canvas, "TOPLEFT", t[3] * w / scale, -t[4] * h / scale)
            pin:Show()
        end
    end
    self:Cover()
end

-- /way towns debug: the badge nearest the mouse on the open map, and every frame on the map around
-- it (what might cover it or be covered by it), to chat.
function Towns:Debug()
    if not (WorldMapFrame and WorldMapFrame:IsShown()) then return ns:Print("Open the world map first.") end
    local mx, my = GetCursorPosition()
    local best, bestD
    for i = 1, used do
        local l, r, b, t = Rect(pins[i])
        if l then
            local d = ((l + r) / 2 - mx) ^ 2 + ((b + t) / 2 - my) ^ 2
            if not bestD or d < bestD then best, bestD = pins[i], d end
        end
    end
    if not best then return ns:Print(("No town badges on this map (%d drawn)."):format(used)) end
    local function Name(f)
        local ok, n = pcall(function() return f.GetDebugName and f:GetDebugName() or f:GetName() end)
        return ok and n or tostring(f)
    end
    local function Textures(f)
        local n = 0
        for _, region in ipairs({ f:GetRegions() }) do
            if region:GetObjectType() == "Texture" and region:IsVisible() and region:GetAlpha() > 0 then n = n + 1 end
        end
        return n
    end
    local function State(f)
        local l, r, b, t = Rect(f)
        return ("%s %dx%d strata %s level %d alpha %.2f eff %.2f shown %s visible %s mouse %s"):format(f:GetObjectType(),
            l and (r - l) or -1, l and (t - b) or -1, tostring(f:GetFrameStrata()), f:GetFrameLevel(), f:GetAlpha(),
            f.GetEffectiveAlpha and f:GetEffectiveAlpha() or -1, tostring(f:IsShown()), tostring(f:IsVisible()),
            tostring(f:IsMouseEnabled()))
    end
    local icon = best.icon
    ns:Print(("Badge %s: %s"):format(best.town and best.town[1] or "?", State(best)))
    ns:Print(("  image: texture %s layer %s alpha %.2f shown %s visible %s"):format(tostring(icon:GetTexture()),
        tostring(icon:GetDrawLayer()), icon:GetAlpha(), tostring(icon:IsShown()), tostring(icon:IsVisible())))
    local bl, br, bb, bt = Rect(best)
    local canvas, n = WorldMapFrame:GetCanvas(), 0
    local function Report(f, depth)
        if f == best then return end
        local l, r, b, t = Rect(f)
        if l and l < br + 4 and r > bl - 4 and b < bt + 4 and t > bb - 4 then
            n = n + 1
            ns:Print(("  %s%s: %s textures %d%s"):format(depth > 0 and "  > " or "", Name(f), State(f), Textures(f),
                hidden[f] and "  [hidden by Waypoint]" or ""))
        end
    end
    for _, f in ipairs({ canvas:GetChildren() }) do
        Report(f, 0)
        for _, inner in ipairs({ f:GetChildren() }) do Report(inner, 1) end
    end
    ns:Print(("  %d other frames around it; canvas level %d strata %s."):format(n, canvas:GetFrameLevel(), tostring(canvas:GetFrameStrata())))
end

ns:On("PLAYER_LOGIN", function()
    if not WorldMapFrame then return end
    local function Refresh() Towns:Refresh() end
    hooksecurefunc(WorldMapFrame, "OnMapChanged", Refresh)
    if WorldMapFrame.OnCanvasScaleChanged then hooksecurefunc(WorldMapFrame, "OnCanvasScaleChanged", Refresh) end
    WorldMapFrame:HookScript("OnShow", Refresh)
    WorldMapFrame:HookScript("OnHide", function() Towns:RestoreAll() end)
    -- Other addons redraw their pins: keep covering the ones that land on a badge.
    local acc = 0
    CreateFrame("Frame"):SetScript("OnUpdate", function(_, elapsed)
        acc = acc + elapsed
        if acc < RECHECK then return end
        acc = 0
        if WorldMapFrame:IsShown() and used > 0 then Towns:Cover() end
    end)
end)
