local _, ns = ...

-- Towns on the world map: a small Waypoint town badge on every town, village, camp and quest hub
-- of your faction (and neutral ones like Booty Bay, on a gold badge), on its zone's map (capitals
-- also on their own map). Hovering shows what's there: innkeeper, repair, bank, vendors, trainers,
-- quartermasters, mailbox, stable master..., and "No flight master" when there isn't one. Clicking
-- navigates there (a request: the arrow's next point, whatever it was following). Ctrl+clicks are
-- the map's as always (MapPins.lua). The towns come from Data/Towns.lua (generated by
-- tools/Waypoint/build_places.py from QuestieDB and the game's map tables). /way towns turns them off.
--
-- Any other icon touching a town badge (Questie's quest givers and townsfolk, other addons' pins,
-- the map's own icons) is hidden while it does, and what its tooltip says goes at the top of the
-- town's tooltip, so nothing is lost. Waypoint's own path and target pins are never hidden.
-- Hidden icons get their look back as soon as they stop touching a town, the map changes or
-- closes, or towns are turned off.
local Towns = {}
ns.TownPins = Towns

local SIZE = 16
local ICON = "Interface\\AddOns\\Waypoint\\Media\\Town"
local ICON_NEUTRAL = "Interface\\AddOns\\Waypoint\\Media\\TownNeutral"
local NO_FLIGHT = { 1, 0.55, 0.2 }
local MAX_ICON = 48  -- on-screen pixels: anything bigger on the canvas isn't an icon (overlays, art)
local PAD = 2        -- pixels around a badge that count as touching it
local RECHECK = 0.5  -- seconds between checks while the map is open (other addons redraw their pins)

local BadgeLevel -- below
local pins, used = {}, 0
local warned -- the badge texture didn't load (the game only finds new files after a restart)

-- Sets the badge's picture, falling back to Waypoint's own icon when the file isn't loaded yet.
local function SetBadge(tex, path)
    if tex:SetTexture(path) == false or not tex:GetTexture() then
        tex:SetTexture(ns.ICON)
        if not warned then
            warned = true
            ns:Print("Town badges need a full game restart to load (showing Waypoint's icon until then).")
        end
    end
end
local byMap -- uiMapID -> { town }
local hidden = setmetatable({}, { __mode = "k" }) -- frame -> { alpha, mouse, pin }

local function Available()
    return ns.Towns ~= nil and ns.Navigate and ns.Navigate:Available()
end

local function MyFaction()
    local f = UnitFactionGroup("player")
    return f == "Alliance" and "A" or f == "Horde" and "H" or nil
end

-- Your faction's towns and neutral ones, by map.
local function Index()
    if byMap then return byMap end
    byMap = {}
    local mine = MyFaction()
    for _, t in ipairs(ns.Towns) do
        if t[5] == "AH" or t[5] == mine then
            byMap[t[2]] = byMap[t[2]] or {}
            table.insert(byMap[t[2]], t)
        end
    end
    return byMap
end

-- The tooltip's lines for a town: { { label, text } }, then whether it has a flight master.
function Towns:Lines(t)
    local out = {}
    for i = 8, #t do
        local label, text = t[i]:match("^([^|]+)|(.*)$")
        if label then out[#out + 1] = { label, text } end
    end
    if t[7] > 0 then out[#out + 1] = { "Quest givers", tostring(t[7]) } end
    return out, t[6]
end

