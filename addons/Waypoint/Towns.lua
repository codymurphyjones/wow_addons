-- A frame's rectangle on screen: left, right, bottom, top (nil when it has none yet).
local function Rect(f)
    local l, r, b, t = f:GetLeft(), f:GetRight(), f:GetBottom(), f:GetTop()
    if not (l and r and b and t) then return nil end
    local s = f:GetEffectiveScale()
    return l * s, r * s, b * s, t * s
end

local function Hide(frame, pin)
    local h = hidden[frame]
    if not h then
        h = { alpha = frame:GetAlpha(), mouse = frame:IsMouseEnabled() }
        hidden[frame] = h
    end
    h.pin, h.seen = pin, true
    frame:SetAlpha(0)
    if frame:IsMouseEnabled() then frame:EnableMouse(false) end
end

local function Restore(frame)
    local h = hidden[frame]
    if not h then return end
    hidden[frame] = nil
    frame:SetAlpha(h.alpha or 1)
    if h.mouse then frame:EnableMouse(true) end
end

function Towns:RestoreAll()
    for frame in pairs(hidden) do Restore(frame) end
end

-- Hides every other icon touching a shown badge, and gives back the ones that stopped touching.
function Towns:Cover()
    for _, h in pairs(hidden) do h.seen = false end
    if used > 0 then
        local canvas = WorldMapFrame:GetCanvas()
        local boxes = {}
        for i = 1, used do
            local l, r, b, t = Rect(pins[i])
            if l then boxes[#boxes + 1] = { pins[i], l - PAD, r + PAD, b - PAD, t + PAD } end
        end
        -- An icon: shown, hoverable (or hidden by us), icon-sized, not Waypoint's own.
        local function Check(f)
            if f.wpTown or f.waypoint or not f:IsShown() or not (f:IsMouseEnabled() or hidden[f]) then return false end
            local l, r, b, t = Rect(f)
            if not (l and r > l and r - l <= MAX_ICON and t - b <= MAX_ICON) then return false end
            for _, box in ipairs(boxes) do
                if l < box[3] and r > box[2] and b < box[5] and t > box[4] then
                    Hide(f, box[1])
                    break
                end
            end
            return true
        end
        -- Pins sit on the canvas, or inside a container there (HereBeDragons pins, which Questie
        -- uses, hold the addon's icon frame in a tiny pin of their own): look one level in.
        for _, f in ipairs({ canvas:GetChildren() }) do
            if not Check(f) and not f.wpTown and not f.waypoint and f:IsShown() then
                for _, inner in ipairs({ f:GetChildren() }) do Check(inner) end
            end
        end
    end
    for frame, h in pairs(hidden) do
        if not h.seen then Restore(frame) end
    end
    -- Whatever happened above, a badge stays visible.
    for i = 1, used do
        if pins[i]:GetAlpha() < 1 then pins[i]:SetAlpha(1) end
    end
end

-- What a hidden icon's own tooltip says: { { left, right, r, g, b } }, or {}. Its addon fills
-- GameTooltip as it would on a real hover; the lines are copied, then it's told the mouse left.
local function Borrow(frame)
    local enter = frame:GetScript("OnEnter") or frame.OnMouseEnter
    if not enter then return {} end
    GameTooltip:Hide()
    GameTooltip:ClearLines()
    local alpha = frame:GetAlpha()
    frame:SetAlpha(hidden[frame] and hidden[frame].alpha or 1) -- some pins only fill the tooltip while visible
    pcall(enter, frame)
    frame:SetAlpha(alpha)
    local lines = {}
    for i = 1, GameTooltip:NumLines() do
        local left, right = _G["GameTooltipTextLeft" .. i], _G["GameTooltipTextRight" .. i]
        local text = left and left:GetText()
        if text and text ~= "" then
            local r, g, b = left:GetTextColor()
            local rt = right and right:IsShown() and right:GetText() or nil
            lines[#lines + 1] = { text, rt, r, g, b }
        end
    end
    local leave = frame:GetScript("OnLeave") or frame.OnMouseLeave
    if leave then pcall(leave, frame) end
    GameTooltip:Hide()
    return lines
end

