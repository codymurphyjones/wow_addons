"""The one instance dataset of the suite: every classic dungeon and raid (and WoW Forever's own
dungeons) with its area and map IDs, recommended levels, final bosses, wings and entrances,
written to addons/shared/Instances.lua (the builds copy it into each addon that lists it in its
TOC). Field Guide, SpyGlass and Group History read it instead of tables of their own.

The facts are tools/_shared/instancedata.py's (Field Guide's builder reads the same module);
QuestieDB's Forever data (read-only, in the game folder) gives the names, the alternative area
IDs and the entrances, and is checked against the instance map IDs. Nothing is fetched.

    python tools/shared/build_instances.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(TOOLS, "_shared"))
import instancedata  # noqa: E402
import paths  # noqa: E402
from luawrite import lua_str  # noqa: E402
from zones import Zones  # noqa: E402

OUT = os.path.join(paths.ADDONS, "shared", "Instances.lua")

HEADER = '''-- GENERATED by tools/shared/build_instances.py from tools/_shared/instancedata.py and QuestieDB
-- (Forever). Do not edit; run the tool again. Field Guide, SpyGlass and Group History load it.
--   list = { { key, name, kind ("dungeon" or "raid"), custom (WoW Forever's own), area (AreaTable
--     ID), areas (its own and QuestieDB's alternatives), instanceID (GetInstanceInfo's 8th value),
--     uiMaps (its floors), from, to (recommended levels), entrance = { uiMapID, x, y } (0-100),
--     entrances (every one), bosses (final bosses: one per wing, any of them ends a run),
--     names (every name it goes by, GetInstanceInfo's among them),
--     wings = { { key, name, entrance, bosses, size, uiMaps (floors only it has), loot (its own
--       page in SpyGlass's loot), names } } } }, by level.
--   Lookups: byKey, byArea, byInstanceID, byUiMap and byName (lower case) = { instance, wing };
--   ns.Instances:Get(key), :ByArea(id), :ByInstanceID(id), :ByMap(uiMapID), :ByName(name),
--   :Find(name, instanceID), :Current(), :Wing(inst, key), :IsFinalBoss(inst, boss, wing).
local _, ns = ...
'''

CODE = '''
local I = { list = list, byKey = {}, byArea = {}, byInstanceID = {}, byUiMap = {}, byName = {} }
ns.Instances = I

local function Low(s)
    if type(s) ~= "string" then return nil end
    local ok, low = pcall(string.lower, s)
    return ok and low or nil
end

for _, inst in ipairs(list) do
    I.byKey[inst.key] = inst
    I.byArea[inst.area] = inst
    I.byInstanceID[inst.instanceID] = inst
end
for _, inst in ipairs(list) do
    for _, area in ipairs(inst.areas) do I.byArea[area] = I.byArea[area] or inst end
    for _, map in ipairs(inst.uiMaps or {}) do I.byUiMap[map] = I.byUiMap[map] or { inst } end
    for _, name in ipairs(inst.names) do I.byName[Low(name)] = I.byName[Low(name)] or { inst } end
end
for _, inst in ipairs(list) do
    for _, wing in ipairs(inst.wings or {}) do
        for _, map in ipairs(wing.uiMaps or {}) do I.byUiMap[map] = { inst, wing } end
        for _, name in ipairs(wing.names or {}) do I.byName[Low(name)] = { inst, wing } end
    end
end

function I:Get(key) return self.byKey[key] end
function I:ByArea(areaID) return self.byArea[areaID] end
function I:ByInstanceID(instanceID) return self.byInstanceID[instanceID] end

-- The instance (and the wing, when the floor is only in one) a dungeon map is in.
function I:ByMap(uiMapID)
    local e = self.byUiMap[uiMapID]
    if e then return e[1], e[2] end
end

-- By any of its names, any case ("Deadmines", "The Deadmines"; "Lower Blackrock Spire" is a wing).
function I:ByName(name)
    local e = self.byName[Low(name)]
    if e then return e[1], e[2] end
end

-- By name first (it can name a wing), then by the instance map ID.
function I:Find(name, instanceID)
    local inst, wing = self:ByName(name)
    if inst then return inst, wing end
    if type(instanceID) == "number" then return self.byInstanceID[instanceID] end
end

-- The instance you're in now (and the wing, if its name says), or nil.
function I:Current()
    if not (IsInInstance and IsInInstance()) then return nil end
    local name, _, _, _, _, _, _, instanceID = GetInstanceInfo()
    return self:Find(name, instanceID)
end

function I:Wing(inst, key)
    for _, wing in ipairs(inst and inst.wings or {}) do
        if wing.key == key then return wing end
    end
end

-- Whether boss is a final boss of the instance (of the wing, when one is given): any case.
function I:IsFinalBoss(inst, boss, wing)
    local list = (wing or inst or {}).bosses
    boss = Low(boss)
    if not (list and boss) then return false end
    for _, name in ipairs(list) do
        if Low(name) == boss then return true end
    end
    return false
end
'''


def pt(p):
    return "{ %d, %.1f, %.1f }" % p


def strs(values):
    return "{ " + ", ".join(lua_str(v) for v in values) + " }"


def ints(values):
    return "{ " + ", ".join(str(v) for v in values) + " }"


def unique(values):
    out = []
    for v in values:
        if v and v not in out:
            out.append(v)
    return out


def build():
    zones = Zones()
    static = instancedata.INSTANCES
    quest = instancedata.load_dungeons({i["area"] for i in static})
    ids = instancedata.instance_ids()
    ui_areas = instancedata.ui_map_areas()
    problems = []
    rows = []
    for s in static:
        area = s["area"]
        q = quest.get(area)
        if not q:
            problems.append("%s: area %d isn't in QuestieDB's dungeons" % (s["key"], area))
            q = {"name": s["key"], "areas": {area}, "entrances": []}
        if ids.get(s["instanceID"]) != area:
            problems.append("%s: QuestieDB maps instance %d to area %s, not %d" % (s["key"], s["instanceID"], ids.get(s["instanceID"]), area))
        areas = sorted(q["areas"])
        entrances = [(m, x, y) for m, x, y in ((zones.map_of(a), x, y) for a, x, y in q["entrances"]) if m]
        maps = set(s.get("uiMaps") or []) | {m for m, a in ui_areas.items() if a in q["areas"]}
        wings = []
        for w in instancedata.WINGS.get(area, []):
            wings.append(w)
            maps |= set(w.get("uiMaps") or [])
        rows.append({"s": s, "name": q["name"], "areas": areas, "entrances": entrances, "maps": sorted(maps), "wings": wings,
                     "names": unique([q["name"], s.get("game")] + list(s.get("aliases") or []))})
    rows.sort(key=lambda r: (r["s"]["levels"], r["name"]))
    return rows, problems


def write(rows, path=OUT):
    out = [HEADER, "local list = {"]
    for r in rows:
        s = r["s"]
        lo, hi = s["levels"]
        parts = ["key = %s" % lua_str(s["key"]), "name = %s" % lua_str(r["name"]), "kind = %s" % lua_str(s["kind"])]
        if s.get("custom"):
            parts.append("custom = true")
        parts += ["area = %d" % s["area"], "areas = %s" % ints(r["areas"]), "instanceID = %d" % s["instanceID"]]
        out.append("    { " + ", ".join(parts) + ",")
        line = "      from = %d, to = %d," % (lo, hi)
        if r["maps"]:
            line += " uiMaps = %s," % ints(r["maps"])
        out.append(line)
        if r["entrances"]:
            out.append("      entrance = %s, entrances = { %s }," % (pt(r["entrances"][0]), ", ".join(pt(e) for e in r["entrances"])))
        out.append("      bosses = %s," % strs(s.get("bosses") or []))
        out.append("      names = %s," % strs(r["names"]))
        if r["wings"]:
            out.append("      wings = {")
            for w in r["wings"]:
                wp = ["key = %s" % lua_str(w["key"]), "name = %s" % lua_str(w["name"]), "entrance = %s" % pt(w["entrance"]),
                      "bosses = %s" % strs(w["bosses"])]
                if w.get("size"):
                    wp.append("size = %d" % w["size"])
                if w.get("uiMaps"):
                    wp.append("uiMaps = %s" % ints(w["uiMaps"]))
                if w.get("loot"):
                    wp.append("loot = %s" % lua_str(w["loot"]))
                if w.get("aliases"):
                    wp.append("names = %s" % strs(w["aliases"]))
                out.append("          { " + ", ".join(wp) + " },")
            out.append("      },")
        out.append("    },")
    out.append("}")
    text = "\n".join(out) + "\n" + CODE
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return text


def main():
    if not os.path.exists(instancedata.DUNGEONS_LUA):
        print("Needs QuestieDB's Forever data: %s" % instancedata.DUNGEONS_LUA)
        return 1
    rows, problems = build()
    for p in problems:
        print("  check: " + p)
    write(rows)
    print("wrote %s: %d instances (%d dungeons, %d raids), %d with wings" % (
        os.path.relpath(OUT, paths.REPO), len(rows), sum(r["s"]["kind"] == "dungeon" for r in rows),
        sum(r["s"]["kind"] == "raid" for r in rows), sum(bool(r["wings"]) for r in rows)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
