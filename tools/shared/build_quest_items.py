"""Every item a quest asks you to carry, with the quests that ask for it, written to
addons/shared/QuestItems.lua (the builds copy it into each addon that lists it in its TOC).

Many quest items aren't Quest-class and aren't quest-bound: Southshore Stout is an ordinary drink
that Valik (535) wants. In game, ns.Items.IsQuestItem asks C_QuestLog.IsOnQuest for the quests
listed here, so the answer doesn't depend on the quest log's collapsed headers or on reading its
objective text. Wally uses it to never sell such an item as junk while you're on the quest.

From QuestieDB's Forever data (read-only, in the game folder): each quest's item objectives, its
requiredSourceItems and the item it hands you (sourceItemId). Items QuestieDB files as Quest class
are left out: the game flags those itself. Nothing is fetched.

    python -I tools/shared/build_quest_items.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(TOOLS, "_shared"))
import paths  # noqa: E402
from questiedb import QuestieDB, lua_list  # noqa: E402

OUT = os.path.join(paths.ADDONS, "shared", "QuestItems.lua")
CLASS_QUEST = 12  # the item class the game already reports as a quest item

HEADER = '''-- GENERATED by tools/shared/build_quest_items.py from QuestieDB (Forever). Do not edit; run the
-- tool again. Wally loads it (ns.Items.IsQuestItem reads it when it's there).
--   ns.QUEST_ITEMS[itemID] = { questID, ... }: the quests that need you to carry that item
--   (objectives, required source items, items a quest hands you). Quest-class items are left out.
local _, ns = ...
ns.QUEST_ITEMS = {
'''


def field(table, i):
    """Index i (1-based) of a Lua array that CBOR gave as a list or a map."""
    if isinstance(table, list):
        return table[i - 1] if len(table) >= i else None
    if isinstance(table, dict):
        return table.get(i)
    return None


def item_ids(q):
    out = set()
    for entry in lua_list(field(q.get('objectives'), 3)):
        item_id = field(entry, 1) if isinstance(entry, (list, dict)) else entry
        if isinstance(item_id, int) and item_id > 0:
            out.add(item_id)
    for item_id in lua_list(q.get('requiredSourceItems')):
        if isinstance(item_id, int) and item_id > 0:
            out.add(item_id)
    given = q.get('sourceItemId')
    if isinstance(given, int) and given > 0:
        out.add(given)
    return out


def main():
    db = QuestieDB.load()
    needs = {}
    for quest_id in db.quest_ids():
        q = db.quest(quest_id)
        if not q:
            continue
        for item_id in item_ids(q):
            needs.setdefault(item_id, set()).add(quest_id)
    skipped = 0
    lines = []
    for item_id in sorted(needs):
        item = db.item(item_id) or {}
        if item.get('class') == CLASS_QUEST:
            skipped += 1
            continue
        lines.append("    [%d] = { %s },\n" % (item_id, ", ".join(str(q) for q in sorted(needs[item_id]))))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        f.writelines(lines)
        f.write("}\n")
    print("QuestItems.lua: %d items (%d Quest-class items left out) -> %s" % (len(lines), skipped, OUT))


if __name__ == "__main__":
    main()
