"""Full-resolution dungeon map art for SpyGlass's dungeon maps (Journal/DungeonMap.lua).

The pictures fetch_pulls.py makes (Media/Pulls/<Key>-<floor>.blp) are Blizzard's dungeon map art
shrunk to 768x512 and DXT1-compressed. The game ships the same art at full size: each floor is
12 tiles of 256 px (4 across, 3 down; the map is the top-left 1002x668), and the dungeon map
draws those tiles straight from the game's files instead. Pack positions don't change: they're
0-100 over that same 1002x668 art.

Which tiles: OpenMap's Data/DungeonMaps.lua (MIT; its tools/map-dungeons/build.py, from the
UiMap tables of build 5.5.4 and checked against the WoW Forever install's own files), read from
the game's AddOns folder. Each SpyGlass instance is matched by its instance (map) ID, each floor by
its name, else by its place in the list when the counts agree. Anything unmatched is reported and
keeps its old picture.

Writes addons/Spyglass/Journal/MapTiles.lua.

    python tools/Spyglass/build_map_tiles.py [path to OpenMap's Data/DungeonMaps.lua]
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "_shared"))
import paths  # noqa: E402

ADDON = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "addons", "Spyglass")
PULLS = os.path.join(ADDON, "Journal", "PullData.lua")
OUT = os.path.join(ADDON, "Journal", "MapTiles.lua")
OPENMAP = os.path.join(paths.GAME_ADDONS, "OpenMap", "Data", "DungeonMaps.lua")


def norm(name):
    return re.sub(r"[^a-z0-9]", "", (name or "").lower().replace("the ", ""))


def spyglass_instances(path):
    """[ (key, instanceID, [ floor names ]) ] in the file's order."""
    out, cur = [], None
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r'\s*\["([^"]+)"\] = \{\s*$', line)  # (keys may hold an apostrophe)
            if m:
                cur = [m.group(1), None, []]
                out.append(cur)
                continue
            if cur is None:
                continue
            m = re.search(r'\binstanceID = (\d+)', line)
            if m and cur[1] is None:
                cur[1] = int(m.group(1))
            m = re.match(r'\s*\{ file = "[^"]*",.*?\bname = "((?:[^"\\]|\\.)*)"', line)
            if m:
                cur[2].append(m.group(1).replace('\\"', '"'))
    return [tuple(i) for i in out if i[1] is not None and i[2]]


def openmap_dungeons(path):
    """{ instance mapID: [ { tiles = [12], name = str or None } ] }."""
    out, cur = {}, None
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r'\s*\[(\d+)\] = \{', line)
            if m:
                cur = out.setdefault(int(m.group(1)), [])
                continue
            m = re.search(r'tiles = \{ ([\d, ]+) \}', line)
            if m and cur is not None:
                tiles = [int(t) for t in m.group(1).split(",")]
                n = re.search(r'\bname = "((?:[^"\\]|\\.)*)"', line)
                if len(tiles) == 12:
                    cur.append({"tiles": tiles, "name": n.group(1) if n else None})
    return out


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else OPENMAP
    if not os.path.exists(source):
        print("OpenMap's Data/DungeonMaps.lua isn't at", source)
        return 1
    om = openmap_dungeons(source)
    sg = spyglass_instances(PULLS)
    result, missing = {}, []
    used = set()
    for key, inst, names in sg:
        floors = om.get(inst) or []
        by_name = {norm(f["name"]): f for f in floors if f["name"]}
        tiles = {}
        for i, name in enumerate(names, 1):
            f = by_name.get(norm(name))
            if not f and len(floors) == len(names):
                f = floors[i - 1]
            if f:
                tiles[i] = f["tiles"]
                used.add(inst)
            else:
                missing.append("%s floor %d (%s)" % (key, i, name))
        if tiles:
            result[key] = tiles
    lines = [
        "local _, ns = ...",
        "-- Generated by tools/Spyglass/build_map_tiles.py. Do not edit.",
        "-- Blizzard's own dungeon map art in the game's files, a floor at a time: 12 tiles of 256 px, row-major",
        "-- (4 across, 3 down; the map is the top-left 1002x668). Which tiles: OpenMap's Data/DungeonMaps.lua",
        "-- (MIT, by the OpenMap contributors), matched to Journal/PullData.lua's floors by instance and name.",
        "-- ns.PullTiles[key][floor] = { 12 file IDs }",
        "ns.PullTiles = {",
    ]
    for key in sorted(result):
        lines.append('  ["%s"] = {' % key)
        for i in sorted(result[key]):
            lines.append("    [%d] = { %s }," % (i, ", ".join(str(t) for t in result[key][i])))
        lines.append("  },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    floors = sum(len(v) for v in result.values())
    print("wrote %s: %d instances, %d floors" % (OUT, len(result), floors))
    if missing:
        print("no full-size art (keeping the old picture):", "; ".join(missing))
    extra = sorted(set(om) - {i for _, i, _ in sg})
    if extra:
        print("OpenMap has maps of instances SpyGlass has no pull data for (map IDs):", extra)
    return 0


if __name__ == "__main__":
    sys.exit(main())
