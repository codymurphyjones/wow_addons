"""Which items vendors sell, from Questie's Forever database (the QuestieDB addon, read-only).

Wealth Planner values these at no more than a vendor charges, and never suggests buying them at
the auction house: whoever lists Maple Seeds for 30s each is counting on buyers who don't know a
reagent vendor has them for a few silver. The vendors' exact prices are learned in game from each
merchant window you open; until then the addon estimates them from the item's sell price.
Writes Data/VendorItems.lua.

questiedb.py is copied from FieldGuide/Tools (copied, not imported: the addons stay apart).

    python tools/WealthPlanner/build_vendor_items.py
"""
import os

import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # sibling modules, also under python -I
from questiedb import QuestieDB, lua_list

ADDON = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "addons", "WealthPlanner")  # tools/WealthPlanner/ builds addons/WealthPlanner/
OUT = os.path.join(ADDON, "Data", "VendorItems.lua")


def main():
    db = QuestieDB.load()
    sold = {}
    for item_id in db.ids('Item-'):
        row = db.item(item_id)
        vendors = lua_list(row.get('vendors')) if row else []
        if vendors:
            sold[item_id] = len(vendors)
    lines = ["-- GENERATED by tools/WealthPlanner/build_vendor_items.py from QuestieDB (Forever). Do not edit.",
             "local _, ns = ...", "",
             "-- [itemID] = how many vendors sell it.",
             "ns.VendorItems = {"]
    ids = sorted(sold)
    for i in range(0, len(ids), 10):
        lines.append("    " + " ".join("[%d] = %d," % (k, sold[k]) for k in ids[i:i + 10]))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d items sold by vendors -> %s" % (len(sold), OUT))


if __name__ == "__main__":
    main()
