"""Finds the areas of the world with only one or two ways in, from the navigation graph.

Red Cloud Mesa has one way down, a walled valley has two: nothing in the game's tables says so, but
the ground does. Each node's clearance is how many steps it is from an edge (a cliff, a wall, water).
Keeping only the nodes with clearance over CORE leaves the open ground as separate regions, joined
only by what was narrower than that. Every node then goes to its nearest region, and each stretch of
border between two regions is an exit: its middle, how wide it is, and where it leads.

Field Guide uses it for the walks quest_walks.py doesn't have: from wherever you stand to a place in
another area, the way goes through an exit. Only areas with at most MAX_EXITS exits, none of them
wider than MAX_WIDTH (past that it isn't a way in, it's open ground the method split in two).

Writes tools/FieldGuide/gates_report.txt (for reading) and addons/FieldGuide/Guides/Gates.lua:
ns.QuestGates[map] = { cell, max, of = { [square] = area }, exits = { [area] = { { north, west }, ... } } },
a square being row * 1024 + column of CELL-yard squares, both counted from nav_reduce.MAX down.

    python tools/FieldGuide/quest_gates.py [map ...]
"""
import collections
import os
import site
import sys

sys.path.append(site.getusersitepackages())  # (scipy: build_all.py runs the scripts with -I)

import numpy as np
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import connected_components, dijkstra

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "Waypoint"))
import nav_pack as NP  # noqa: E402

CORE = 3          # steps from an edge (25 yards): what's narrower than twice this is a passage
MIN_REGION = 150  # nodes (about 10,000 square yards): smaller isn't an area
MAX_EXITS = 2
MAX_WIDTH = 120   # yards
CELL = 66.666667  # yards: as quest_walks.py
OUT = os.path.join(NP.ROOT, "addons", "FieldGuide", "Guides", "Gates.lua")
REPORT = os.path.join(HERE, "gates_report.txt")


def mutual(N, L):
    """Walks that go both ways, between land nodes: the ground as an undirected graph."""
    keep = (L[:, 2] == 0) & (N[L[:, 0], 4] == 0) & (N[L[:, 1], 4] == 0)
    a, b = L[keep, 0], L[keep, 1]
    n = len(N)
    fwd = a * n + b
    both = np.isin(fwd, b * n + a)
    return a[both], b[both]


def regions(N, L):
    n = len(N)
    a, b = mutual(N, L)
    g = csr_matrix((np.ones(len(a), dtype=np.float32), (a, b)), shape=(n, n))
    degree = np.bincount(a, minlength=n)
    edge = np.nonzero(degree < 4)[0]
    clearance = dijkstra(g, directed=False, indices=edge, unweighted=True, min_only=True, limit=CORE + 1)
    core = np.isfinite(clearance) == False  # (further from an edge than the limit reaches)
    core &= degree > 0
    keep = core[a] & core[b]
    gc = csr_matrix((np.ones(keep.sum(), dtype=np.int8), (a[keep], b[keep])), shape=(n, n))
    _, labels = connected_components(gc, directed=False)
    labels = np.where(core, labels, -1)
    sizes = np.bincount(labels[labels >= 0])
    big = np.nonzero(sizes >= MIN_REGION)[0]
    print("  %d land nodes, %d open, %d regions" % ((degree > 0).sum(), core.sum(), len(big)), flush=True)
    seeds = np.nonzero(np.isin(labels, big))[0]
    # Every node to its nearest region.
    _, _, sources = dijkstra(g, directed=False, indices=seeds, unweighted=True, min_only=True,
                             return_predecessors=True)
    owner = np.where(sources >= 0, labels[np.maximum(sources, 0)], -1)
    return a, b, owner


def exits(N, a, b, owner):
    """Each region's exits: stretches of border to another region, joined where they touch."""
    _, _, n, w, _ = NP.positions(N)
    cross = (owner[a] >= 0) & (owner[b] >= 0) & (owner[a] < owner[b])
    pairs = collections.defaultdict(list)
    for x, y in zip(a[cross], b[cross]):
        pairs[(int(owner[x]), int(owner[y]))].append((int(x), int(y)))
    found = collections.defaultdict(list)
    for (ra, rb), links in pairs.items():
        pts = np.array([[n[x], w[x]] for x, _ in links])
        # Links within 40 yards of each other are one exit.
        left = list(range(len(links)))
        while left:
            group, stack = [], [left.pop()]
            while stack:
                i = stack.pop()
                group.append(i)
                near = [j for j in left if np.hypot(*(pts[i] - pts[j])) <= 40]
                for j in near:
                    left.remove(j)
                    stack.append(j)
            mid = pts[group].mean(axis=0)
            width = max(np.ptp(pts[group, 0]), np.ptp(pts[group, 1])) + 8
            found[ra].append((float(mid[0]), float(mid[1]), float(width), rb))
            found[rb].append((float(mid[0]), float(mid[1]), float(width), ra))
    return found


def main(argv):
    lines = ["-- GENERATED by tools/FieldGuide/quest_gates.py from Waypoint's navigation graph. Do not edit.",
             "-- The areas with one or two ways in, by square, and their exits.",
             "local _, ns = ...", "ns.QuestGates = {"]
    report = []
    for mapid in [int(x) for x in argv] or [0, 1, 2991]:
        print("map", mapid, flush=True)
        z = np.load(os.path.join(NP.NAV, "%d.graph.npz" % mapid))
        N, L = z["nodes"].astype(np.int64), z["links"].astype(np.int64)
        a, b, owner = regions(N, L)
        found = exits(N, a, b, owner)
        _, _, n, w, _ = NP.positions(N)
        counts = np.bincount(owner[owner >= 0])
        kept = 0
        of, ways = {}, []
        for r in np.nonzero(counts)[0]:
            r = int(r)
            mine = found.get(r, [])
            if not mine or len(mine) > MAX_EXITS or max(e[2] for e in mine) > MAX_WIDTH:
                continue
            at = owner == r
            cn, cw = float(n[at].mean()), float(w[at].mean())
            kept += 1
            report.append("map %d: %d exit(s), %d nodes, around %.0f, %.0f: %s" % (
                mapid, len(mine), counts[r], cn, cw,
                "; ".join("%.0f,%.0f %.0f yd wide" % e[:3] for e in mine)))
            ways.append(mine)
            keys = (((NP.nr.MAX - n[at]) // CELL).astype(np.int64) * 1024
                    + ((NP.nr.MAX - w[at]) // CELL).astype(np.int64))
            for key in np.unique(keys):
                of.setdefault(int(key), kept)
        lines.append("    [%d] = { cell = %.6f, max = %.6f, of = {" % (mapid, CELL, NP.nr.MAX))
        keys = sorted(of)
        for i in range(0, len(keys), 12):
            lines.append("        " + " ".join("[%d] = %d," % (k, of[k]) for k in keys[i:i + 12]))
        lines.append("    }, exits = {")
        for mine in ways:
            lines.append("        { %s }," % ", ".join("{ %.0f, %.0f }" % e[:2] for e in mine))
        lines.append("    } },")
        print("  %d regions with %d exits or fewer" % (kept, MAX_EXITS), flush=True)
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    with open(REPORT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(report) + "\n")
    print("%d areas -> %s, %.2f MB" % (len(report), OUT, os.path.getsize(OUT) / 1e6))


if __name__ == "__main__":
    main(sys.argv[1:])
