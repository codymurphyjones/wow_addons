"""Task areas for Field Guide's leveling planner: where the work is, whatever zone it's in.

A task is one thing a quest asks you to do in one place: each objective part that has its own spot
(Data.lua's g[i].p, one stop each when the quest has sp), or the quest's objective spot when it has
one place, or its hand-in when there's nothing to do but talk. The leveling planner (Tasks.lua) picks
areas by XP a minute and orders the tasks inside them; pick-ups and hand-ins come with the quests.

Spots are clustered in world yards (the continent's coordinates, check_water.world), so an area can
straddle a zone border; never a continent. Like quest_zones.py's quest areas: tasks within LINK
yards and LEVEL_LINK levels join, and an area spanning more than LEVEL_SPAN levels splits at its
biggest level gap, one wider than SPREAD yards across splits by its two farthest tasks.

Called by build_guides.py's write(); writes addons/FieldGuide/Guides/Areas.lua:
    ns.TaskAreas = { Alliance = { { c = { uiMapID, x, y }, lo = 10, hi = 12, t = { qid, part, ... } }, ... },
                     Horde = { ... } }
part: the g index of the task's objective (one stop of a quest with sp), 0 for the quest's one
objective place, -1 for the hand-in of a quest with nothing else to do.
"""
import collections
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

LINK = 260        # yards: tasks this close join an area
LEVEL_LINK = 2    # ...when their quests are this close in level
LEVEL_SPAN = 3    # an area spanning more levels splits at its biggest level gap
SPREAD = 900      # yards: an area wider than this splits in two
MAX_TASKS = 18    # an area with more tasks than this splits in two


class Task:
    __slots__ = ('qid', 'part', 'spot', 'level', 'c', 'n', 'w')

    def __init__(self, qid, part, spot, level, world):
        self.qid, self.part, self.spot, self.level = qid, part, spot, level
        self.c, self.n, self.w = world


def _dist(a, b):
    return math.hypot(a.n - b.n, a.w - b.w)


def _clusters(tasks):
    """Union-find on LINK yards and LEVEL_LINK levels, one continent at a time."""
    parent = list(range(len(tasks)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    cell = collections.defaultdict(list)
    for i, t in enumerate(tasks):
        cell[(t.c, int(t.n // LINK), int(t.w // LINK))].append(i)
    for (c, cn, cw), members in cell.items():
        for dn in (-1, 0, 1):
            for dw in (-1, 0, 1):
                for j in cell.get((c, cn + dn, cw + dw), ()):
                    for i in members:
                        if i < j and abs(tasks[i].level - tasks[j].level) <= LEVEL_LINK and _dist(tasks[i], tasks[j]) <= LINK:
                            parent[find(i)] = find(j)
    groups = collections.defaultdict(list)
    for i, t in enumerate(tasks):
        groups[find(i)].append(t)
    return list(groups.values())


def _split(group):
    """Areas small enough to be one place at one level: [ [Task] ]."""
    out, todo = [], [group]
    while todo:
        g = todo.pop()
        levels = sorted({t.level for t in g})
        if levels[-1] - levels[0] > LEVEL_SPAN:
            gap = max(range(1, len(levels)), key=lambda i: levels[i] - levels[i - 1])
            cut = levels[gap]
            todo += [[t for t in g if t.level < cut], [t for t in g if t.level >= cut]]
            continue
        if len(g) > 1:
            a = max(g, key=lambda t: _dist(t, g[0]))
            b = max(g, key=lambda t: _dist(t, a))
            if _dist(a, b) > SPREAD or len(g) > MAX_TASKS:
                near_a = [t for t in g if _dist(t, a) <= _dist(t, b)]
                near_b = [t for t in g if _dist(t, a) > _dist(t, b)]
                if near_a and near_b:
                    todo += [near_a, near_b]
                    continue
        out.append(g)
    return out


def _centre(g):
    """The task nearest the middle (a real spot, on a real map)."""
    n = sum(t.n for t in g) / len(g)
    w = sum(t.w for t in g) / len(g)
    return min(g, key=lambda t: math.hypot(t.n - n, t.w - w))


def areas(tasks):
    """tasks: [Task] (world coordinates set). The areas, busiest first within a level: [ [Task] ]."""
    out = []
    for group in _clusters(tasks):
        out += _split(group)
    out.sort(key=lambda g: (min(t.level for t in g), -len(g)))
    return out


def lua(faction_areas, pt):
    """faction_areas: { faction: [ [Task] ] }. Areas.lua's text. pt(spot) -> 'map, x, y'."""
    lines = ['-- GENERATED by tools/FieldGuide/build_guides.py (task_areas.py). Do not edit.',
             '-- Where the leveling planner\'s work is, whatever zone it\'s in: clusters of quest tasks.',
             '-- c = the area\'s middle task spot; lo / hi = its quests\' levels; t = { questID, part, ... }:',
             '-- part = the g index of one objective stop, 0 the quest\'s one objective place, -1 its hand-in',
             '-- (a quest with nothing else to do).',
             'local _, ns = ...', '', 'ns.TaskAreas = {']
    for faction in sorted(faction_areas):
        lines.append('    %s = {' % faction)
        for g in faction_areas[faction]:
            c = _centre(g)
            seen, pairs = set(), []
            for t in sorted(g, key=lambda t: (t.qid, t.part)):
                if (t.qid, t.part) not in seen:
                    seen.add((t.qid, t.part))
                    pairs.append('%d, %d' % (t.qid, t.part))
            lines.append('        { c = { %s }, lo = %d, hi = %d, t = { %s } },'
                         % (pt(c.spot), min(t.level for t in g), max(t.level for t in g), ', '.join(pairs)))
        lines.append('    },')
    lines.append('}')
    return '\n'.join(lines) + '\n'
