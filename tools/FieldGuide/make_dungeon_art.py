"""The pictures of the dungeon picker (addons/FieldGuide/Media/Dungeons/*.tga), made small from the ones
Spyglass ships (addons/Spyglass/Media/Zones/inst-*.tga, drawn by tools/Spyglass/fetch_zone_art.py), so
Field Guide has them without Spyglass installed. And Guides/DungeonArt.lua, which says which dungeons
have one: the game can't tell, SetTexture answers true for a missing file too.

    python -I tools/FieldGuide/make_dungeon_art.py
"""
import os
import re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SOURCE = os.path.join(REPO, "addons", "Spyglass", "Media", "Zones")
OUT = os.path.join(REPO, "addons", "FieldGuide", "Media", "Dungeons")
LIST = os.path.join(REPO, "addons", "FieldGuide", "Guides", "DungeonArt.lua")
SIZE = (128, 64)
# A dungeon entered wing by wing: Spyglass pictures the wings, the picker lists the dungeon.
WINGS = {"ScarletMonastery": "ScarletMonasteryGraveyard", "DireMaul": "DireMaulEast",
         "BlackrockSpire": "LowerBlackrockSpire"}


def main():
    text = open(os.path.join(REPO, "addons", "shared", "Instances.lua"), encoding="utf-8").read()
    keys = re.findall(r'\{ key = "([^"]+)", name = "[^"]+", kind = "dungeon"', text)
    os.makedirs(OUT, exist_ok=True)
    rows, missing = [], []
    for key in keys:
        plain = re.sub(r"[^A-Za-z0-9]", "", WINGS.get(key, key))
        path = os.path.join(SOURCE, "inst-%s.tga" % plain)
        if not os.path.exists(path):
            missing.append(key)
            continue
        Image.open(path).convert("RGB").resize(SIZE, Image.LANCZOS).save(os.path.join(OUT, plain + ".tga"))
        rows.append('    ["%s"] = "%s",' % (key, plain))
    with open(LIST, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tools/FieldGuide/make_dungeon_art.py. Do not edit.\n")
        f.write("local _, ns = ...\n\n-- Dungeons with a picture: Media\\Dungeons\\<name>.tga, by key in shared\\Instances.lua.\n")
        f.write("ns.DungeonArt = {\n" + "\n".join(rows) + "\n}\n")
    print("%d pictures in %s; none for: %s" % (len(rows), OUT, ", ".join(missing) or "nothing"))


if __name__ == "__main__":
    main()
