"""Real walks between the quest points of a zone, for Field Guide's route order.

Straight lines lie inside a zone too: Narache and Bloodhoof Village look 500 yards apart, and the
walk is 1,200 through the mesa's one way down. A route planned on straight lines leaves its hand-ins
behind and comes back for them. This walks Waypoint's navigation graph (tools/Waypoint/.nav, the one
the arrow routes on, diagonals included), taking only the drops that do no damage, from each quest
point to the others on its zone.

Only the pairs a straight line gets badly wrong are kept (MIN_RATIO, MIN_EXTRA): everywhere else
Engine.lua's straight line stands, so the file stays small.

Output: addons/FieldGuide/Guides/Walks.lua, ns.QuestWalks[continent] = { cell, max, rows = { [from
square] = { [to square] = yards } } }. A square is row * 1024 + column of CELL-yard squares, both
counted from nav_reduce.MAX down.

    python tools/FieldGuide/quest_walks.py
"""
import collections
import math
import os
import re
import site
import sys

sys.path.append(site.getusersitepackages())  # (scipy: build_all.py runs the scripts with -I)

import numpy as np  # noqa: E402
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import connected_components, dijkstra
from scipy.spatial import cKDTree

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "Waypoint"))
import zone_walks as Z  # noqa: E402
import nav_pack as NP  # noqa: E402

C = Z.C
ROOT = Z.ROOT
OUT = os.path.join(ROOT, "addons", "FieldGuide", "Guides", "Walks.lua")
CELL = 66.666667  # yards: a point's square, so a place you stand near one finds it
MIN_RATIO = 1.3   # the walk is at least this many times the straight line...
MIN_EXTRA = 150   # ...and this many yards longer
REACH = 9000      # yards: no quest walk within a zone is longer
NEAR = 30         # yards from a point its node may be
BATCH = 100       # sources at a time


def quest_points(assign):
    """continent -> { uiMapID: { (north, west) } }: every pick-up, hand-in and first objective."""
    text = open(Z.DATA, encoding="utf-8").read()
    found = set(re.findall(r"\b[at] = \{ (\d+), ([\d.]+), ([\d.]+)", text))
    found |= set(re.findall(r"\bo = \{ \{ (\d+), ([\d.]+), ([\d.]+)", text))
    out = collections.defaultdict(lambda: collections.defaultdict(set))
    for ui, x, y in found:
        w = C.world(assign, int(ui), float(x) / 100, float(y) / 100)
        if w:
            out[w[0]][int(ui)].add((w[1], w[2]))
    return out


def graph(mapid):
    """The map's nodes' places, sizes and walks (a sparse matrix of yards), and which nodes are on the
    map's main ground: the biggest stretch you can walk both ways. A ledge or a rooftop isn't on it,
    and a quest point that lands on one would find no walk to anywhere."""
    z = np.load(os.path.join(NP.NAV, "%d.graph.npz" % mapid))
    N, L = z["nodes"].astype(np.int64), z["links"].astype(np.int64)
    L = np.concatenate([L, NP.diagonals(N, L)])
    walk, swim, usable = NP.edge_costs(N, L)
    cost = (walk + swim) * NP.RUN
    keep = usable & (cost > 0)
    g = csr_matrix((cost[keep], (L[keep, 0], L[keep, 1])), shape=(len(N), len(N)))
    _, _, n, w, _ = NP.positions(N)
    _, parts = connected_components(g, directed=True, connection="strong")
    main_ground = parts == np.bincount(parts).argmax()
    return np.stack([n, w], axis=1), N[:, 8], g, main_ground


def main():
    assign = Z.assignments()
    points = quest_points(assign)
    lines = ["-- GENERATED by tools/FieldGuide/quest_walks.py from Waypoint's navigation graph. Do not edit.",
             "-- Real walks between a zone's quest points, where a straight line is badly wrong.",
             "local _, ns = ...", "ns.QuestWalks = {"]
    total = 0
    for cont in sorted(points):
        if not os.path.exists(os.path.join(NP.NAV, "%d.graph.npz" % cont)):
            continue
        at, size, g, ground = graph(cont)
        tree = cKDTree(at[ground])
        ids = np.nonzero(ground)[0]
        rows = collections.defaultdict(dict)
        nodes = collections.defaultdict(list)  # node -> [ (key, north, west, uiMapID) ]
        for ui, pts in points[cont].items():
            for n, w in pts:
                near = tree.query_ball_point([n, w], NEAR)
                if near:
                    node = int(ids[max(near, key=lambda i: size[ids[i]])])  # the open ground, not a ledge beside it
                    key = int((NP.nr.MAX - n) // CELL) * 1024 + int((NP.nr.MAX - w) // CELL)
                    nodes[node].append((key, n, w, ui))
        sources = sorted(nodes)
        print("map", cont, len(sources), "points,", g.nnz, "links", flush=True)
        for start in range(0, len(sources), BATCH):
            part = sources[start:start + BATCH]
            dist = dijkstra(g, directed=True, indices=part, limit=REACH)
            for i, a in enumerate(part):
                for ka, an, aw, ui in nodes[a]:
                    for b in sources:
                        d = dist[i, b]
                        # (No walk found says more about the node than the place, a ledge or an
                        # upper floor: nothing is kept, and Engine.lua's straight line stands.)
                        if not np.isfinite(d):
                            continue
                        for kb, bn, bw, ub in nodes[b]:
                            if ub != ui:
                                continue
                            straight = math.hypot(an - bn, aw - bw)
                            if d >= straight * MIN_RATIO and d - straight >= MIN_EXTRA:
                                rows[ka][kb] = int(d)
            print("  %d of %d" % (min(start + BATCH, len(sources)), len(sources)), flush=True)
        pairs = sum(len(r) for r in rows.values())
        total += pairs
        print("  %d pairs" % pairs, flush=True)
        lines.append("    [%d] = { cell = %.6f, max = %.6f, rows = {" % (cont, CELL, NP.nr.MAX))
        for ka in sorted(rows):
            lines.append("        [%d] = { %s }," % (ka, ", ".join("[%d] = %d" % (k, rows[ka][k]) for k in sorted(rows[ka]))))
        lines.append("    } },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d pairs -> %s, %.2f MB" % (total, OUT, os.path.getsize(OUT) / 1e6))


if __name__ == "__main__":
    main()
